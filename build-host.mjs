#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 host.js：rolldown 把 host.ts 及其 `./lib/*` 依赖打成单文件 ESM，落在**包根**
// （与源码同目录，故 `import.meta.dirname` 的语义与源码态完全一致）。
// 编排（依赖段外部化、输出守卫、region 路径规范化、moduleIds 结构性判据）统一实现在
// @jayyuen66/dsh-plugin-shared/lib/build-host，一处可改；本文件只声明本仓的入口、产物
// 与生成头。为什么必须有打包这一步（Node 对 node_modules 里的 .ts 直接抛
// ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING）、为什么外部化按包名段判——见 shared
// 同名切面的文件头。不产 .d.ts：插件包对外没有 TS API——dsh 按包名载入运行，没有人
// import 它。
import path from "node:path";
import { createRequire } from "node:module";
import { rolldown } from "rolldown";
import { buildHostEntries } from "@jayyuen66/dsh-plugin-shared/lib/build-host";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";
import { rolldownDecorators } from "@jayyuen66/dsh-plugin-shared/lib/decorator-lowering";

// 测试按「脚本自己导出它用的工具」这一规则从本模块导入 singleEntryChunk。
export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

// 装饰器降级要一枚 tsc：接受标准装饰器语法的只有 tsc 自己（rolldown 原样保留 `@Remote(…)`
// 写出非法 JS，见 shared 同名切面的文件头）。入口在本仓解析——shared 不能替消费方解析
// 它自己没声明的依赖。
const tscEntry = path.join(
  path.dirname(createRequire(import.meta.url).resolve("typescript/package.json")),
  "bin",
  "tsc",
);

/** 生成 host.js 的完整文本。 */
export async function buildHost() {
  const artifacts = await buildHostEntries({
    root,
    rolldown,
    plugins: [rolldownDecorators({ tscEntry })],
    entries: [
      {
        source: "host.ts",
        output: "host.js",
        header:
          "// GENERATED by build-host.mjs — edit host.ts / lib/*.ts, then run `node build-host.mjs`.\n",
      },
    ],
  });
  const artifact = artifacts.find((item) => item.output === "host.js");
  if (artifact === undefined) {
    throw new Error("buildHostEntries 交回的产物清单里没有 host.js");
  }
  return artifact.code;
}

async function main() {
  const out = await buildHost();
  await writeArtifact(path.join(root, "host.js"), out);
  console.info("host.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    // 用 exitCode 而不是 process.exit：后者会在 stdout/stderr 管道被占满时截断错误输出。
    console.error(error);
    process.exitCode = 1;
  }
}
